#!/usr/bin/env python3
"""Generate the language bindings from the ABI description (abi/vbm_sse.abi.json). Usage: gen_bindings.py ROOT   (writes ROOT/bindings/...; scripts/gen-bindings.sh wraps it).
Everything the bindings contain that depends on the ABI is generated here: constants, struct layouts, function prototypes, the error types, and the report reader. The only hand-written
files are the loaders (bindings/python/vbm_sse/loader.py, bindings/rust/loader.rs: where the library is found) and the manifests. The bindings decide nothing about SSE: the report
is read, never re-computed (docs/decisions/0001-vbm-sse.md: the boundary never decides)."""
import json, os, re, sys

HDR = "GENERATED by scripts/gen_bindings.py from abi/vbm_sse.abi.json: do not edit (scripts/gen-bindings.sh regenerates; Tier 1 checks the committed copy equals the regenerated one)."

def camel(n):
    return n.capitalize()

# ---------------------------------------------------------------- Python
PY_SCALAR = {"u8": "ctypes.c_uint8", "u64": "ctypes.c_uint64", "int": "ctypes.c_int", "size": "ctypes.c_size_t", "ptr": "ctypes.c_void_p", "void": "None"}

def py_type(t):
    if t in PY_SCALAR: return PY_SCALAR[t]
    k, _, n = t.partition(":")
    if k == "ptr" and n == "ptr": return "ctypes.POINTER(ctypes.c_void_p)"
    if k == "ptr": return "ctypes.POINTER(%s)" % (PY_SCALAR[n] if n in PY_SCALAR else n)
    if k == "opaque": return "ctypes.c_void_p"
    if k == "struct": return n
    raise SystemExit("gen_bindings: unknown abstract type " + t)

def gen_python(d):
    r = d["report"]
    o = ['"""%s"""' % HDR, "import ctypes", "from . import loader", "",
         "ABI_VERSION = %d" % d["abi_version"], "REPORT_WORD_BYTES = %d" % r["word_bytes"], "REPORT_HEADER_WORDS = %d" % len(r["header"]), "REPORT_EVENT_WORDS = %d" % len(r["event"]), ""]
    for e in d["errors"]: o.append("%s = %d" % (e["name"], e["value"]))
    o.append("")
    for s in d["structs"]:
        o += ["class %s(ctypes.Structure):" % s["name"], "    _fields_ = [" + ", ".join('("%s", %s)' % (f["name"], py_type(f["type"])) for f in s["fields"]) + "]", ""]
    o += ["_lib = loader.load()", ""]
    for f in d["functions"]:
        o += ["%s = _lib.%s" % (f["name"], f["name"]),
              "%s.argtypes = [%s]" % (f["name"], ", ".join(py_type(p["type"]) for p in f["params"])), "%s.restype = %s" % (f["name"], py_type(f["ret"])), ""]
    o += ["", "class Error(Exception):", '    """A non-OK result code of the library: .code is the ABI code, .name its name."""',
          "    def __init__(self, code, name):", '        super().__init__("vbm-sse: %s (code %d)" % (name, code))', "        self.code = code", "        self.name = name", ""]
    errs = [e for e in d["errors"] if e["value"] != 0]
    for e in errs: o += ["class SSE%sError(Error):" % camel(e["name"]), "    pass", ""]
    o.append("_ERRORS = {" + ", ".join("%s: (SSE%sError, %r)" % (e["name"], camel(e["name"]), e["name"]) for e in errs) + "}")
    o += ["", "def _raise(code):", "    cls, name = _ERRORS.get(code, (Error, 'UNKNOWN'))", "    raise cls(code, name)", ""]
    o.append(PY_READER)
    return "\n".join(o) + "\n"

PY_READER = '''
class Event:
    """One dispatched event: type (b"message" unless an `event` field set one), data (the `data` lines joined by LF) and the last event ID at its dispatch: all bytes, as they are in the stream."""
    __slots__ = ("type", "data", "last_event_id")
    def __init__(self, type, data, last_event_id): self.type, self.data, self.last_event_id = type, data, last_event_id
    def __eq__(self, other): return isinstance(other, Event) and (self.type, self.data, self.last_event_id) == (other.type, other.data, other.last_event_id)
    def __hash__(self): return hash((self.type, self.data, self.last_event_id))
    def __repr__(self): return "Event(%r, %r, %r)" % (self.type, self.data, self.last_event_id)


class Report:
    """What one chunk did: the events it completed, the last event ID string after it (bytes) and the reconnection time in milliseconds (None until a `retry` field sets it; saturated at 2**64 - 1)."""
    __slots__ = ("events", "last_event_id", "retry")
    def __init__(self, events, last_event_id, retry): self.events, self.last_event_id, self.retry = events, last_event_id, retry
    def __repr__(self): return "Report(%r, %r, %r)" % (self.events, self.last_event_id, self.retry)


def _read_report(raw):
    """The report of include/vbm_sse.h, read strictly: every length is checked, nothing may follow; a malformed report raises SSEInternalError (it is the library's, not the stream's)."""
    n, i = len(raw), 0
    def word():
        nonlocal i
        if i + REPORT_WORD_BYTES > n: _raise(INTERNAL)
        w = int.from_bytes(raw[i:i + REPORT_WORD_BYTES], "little"); i += REPORT_WORD_BYTES
        return w
    def take(k):
        nonlocal i
        if k > n - i: _raise(INTERNAL)
        s = raw[i:i + k]; i += k
        return s
    count, retry_set, retry, id_len = word(), word(), word(), word()
    last_id = take(id_len)
    events = []
    for _ in range(count):
        tl, dl, il = word(), word(), word()
        events.append(Event(take(tl), take(dl), take(il)))
    if i != n: _raise(INTERNAL)
    return Report(events, last_id, retry if retry_set == 1 else None)


class Reader:
    """A Server-Sent Events reader (HTML Standard 9.2.5 and 9.2.6). feed(chunk) takes the next chunk of the stream (bytes, cut anywhere) and returns the Report of that chunk; the events do not depend on the cuts.
    Use it as a context manager or call close()."""
    def __init__(self):
        out = ctypes.c_void_p()
        rc = vbm_sse_new(ctypes.byref(out))
        if rc != OK: _raise(rc)
        self._r = out
    def feed(self, data):
        if not self._r: raise ValueError("vbm-sse: the reader is closed")
        data = bytes(data)
        rep = vbm_sse_report()
        rc = vbm_sse_feed(self._r, ctypes.cast(ctypes.c_char_p(data), ctypes.POINTER(ctypes.c_uint8)), len(data), ctypes.byref(rep))
        if rc != OK: _raise(rc)
        return _read_report(ctypes.string_at(rep.bytes, rep.nbytes))
    def close(self):
        if self._r:
            vbm_sse_free(self._r); self._r = None
    def __enter__(self): return self
    def __exit__(self, *exc): self.close()
    def __del__(self):
        try: self.close()
        except Exception: pass
'''

PY_INIT = '''"""%s"""
from ._generated import (Reader, Report, Event, Error, ABI_VERSION, %s)
__all__ = ["Reader", "Report", "Event", "Error", "ABI_VERSION", %s]
'''

def gen_python_init(d):
    names = ["SSE%sError" % camel(e["name"]) for e in d["errors"] if e["value"] != 0]
    return PY_INIT % (HDR, ", ".join(names), ", ".join('"%s"' % n for n in names))

# ---------------------------------------------------------------- Rust
RS_SCALAR = {"u8": "u8", "u64": "u64", "int": "c_int", "size": "usize"}

def rs_type(t, c=""):
    const = "const" if re.match(r"\s*const\b", c) else "mut"
    if t == "void": return "()"
    if t in RS_SCALAR: return RS_SCALAR[t]
    if t == "ptr": return "*%s c_void" % const
    k, _, n = t.partition(":")
    if k == "ptr" and n == "ptr": return "*mut *mut c_void"
    if k == "ptr": return "*%s %s" % (const, RS_SCALAR.get(n, n))
    if k == "opaque": return "*mut c_void"
    if k == "struct": return n
    raise SystemExit("gen_bindings: unknown abstract type " + t)

def split_params(c):
    inner = c.split("(", 1)[1].rsplit(")", 1)[0]
    return [p.strip() for p in inner.split(",")]

def gen_rust_sys(d):
    r = d["report"]
    o = ["// " + HDR, "#![allow(non_camel_case_types, non_upper_case_globals, dead_code)]", "use std::os::raw::{c_int, c_void};", "",
         "pub const ABI_VERSION: u32 = %d;" % d["abi_version"], "pub const REPORT_WORD_BYTES: usize = %d;" % r["word_bytes"], ""]
    for e in d["errors"]: o.append("pub const VBM_SSE_%s: c_int = %d;" % (e["name"], e["value"]))
    o.append("")
    for s in d["structs"]:
        o += ["#[repr(C)]", "#[derive(Clone, Copy)]", "pub struct %s {" % s["name"]]
        o += ["    pub %s: %s," % (f["name"], rs_type(f["type"], f["c"])) for f in s["fields"]]
        o += ["}", ""]
    o += ['#[link(name = "vbm_sse")]', 'extern "C" {']
    for f in d["functions"]:
        cs = split_params(f["c"])
        ps = ", ".join("%s: %s" % (p["name"], rs_type(p["type"], c)) for p, c in zip(f["params"], cs))
        rt = "" if f["ret"] == "void" else " -> " + rs_type(f["ret"])
        o.append("    pub fn %s(%s)%s;" % (f["name"], ps, rt))
    o += ["}", ""]
    return "\n".join(o)

RS_LIB = '''// @@HDR@@
//! vbm-sse: safe bindings over the C ABI of libvbm_sse. `Reader::feed` takes the next chunk of a Server-Sent Events stream and returns the `Report` of that chunk, read from the library's report;
//! the library decides what an event is.
pub mod sys;
use std::os::raw::c_void;
use sys::*;

/// One dispatched event: its type (`message` unless an `event` field set one), its data and the last event ID at dispatch; bytes, as they are in the stream.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Event {
    pub type_: Vec<u8>,
    pub data: Vec<u8>,
    pub last_event_id: Vec<u8>,
}

/// What one chunk did: the events it completed, the last event ID string after it and the reconnection time in milliseconds (`None` until a `retry` field sets it; saturated at `u64::MAX`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Report {
    pub events: Vec<Event>,
    pub last_event_id: Vec<u8>,
    pub retry: Option<u64>,
}

/// A non-OK result of the library (`code` is the ABI code).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Error {
@@VARIANTS@@
    Unknown(i32),
}

impl Error {
    pub fn code(&self) -> i32 {
        match self {
@@CODES@@
            Error::Unknown(c) => *c,
        }
    }
    fn from_code(c: i32) -> Error {
        match c {
@@FROM@@
            c => Error::Unknown(c),
        }
    }
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result { write!(f, "vbm-sse: {:?} (code {})", self, self.code()) }
}
impl std::error::Error for Error {}

/// A reader. `feed` the stream's chunks in order; the events do not depend on how the stream is cut.
pub struct Reader(*mut c_void);

impl Reader {
    pub fn new() -> Result<Reader, Error> {
        let mut p: *mut c_void = std::ptr::null_mut();
        let rc = unsafe { vbm_sse_new(&mut p) };
        if rc != VBM_SSE_OK { return Err(Error::from_code(rc)); }
        Ok(Reader(p))
    }

    pub fn feed(&mut self, chunk: &[u8]) -> Result<Report, Error> {
        let mut rep = vbm_sse_report { bytes: std::ptr::null(), nbytes: 0 };
        let rc = unsafe { vbm_sse_feed(self.0, chunk.as_ptr(), chunk.len(), &mut rep) };
        if rc != VBM_SSE_OK { return Err(Error::from_code(rc)); }
        let raw: &[u8] = if rep.nbytes == 0 { &[] } else { unsafe { std::slice::from_raw_parts(rep.bytes, rep.nbytes) } };
        read_report(raw)
    }
}

impl Drop for Reader {
    fn drop(&mut self) { unsafe { vbm_sse_free(self.0) } }
}

struct Cursor<'a> { b: &'a [u8], i: usize }
impl<'a> Cursor<'a> {
    fn word(&mut self) -> Result<u64, Error> {
        if self.b.len() - self.i < REPORT_WORD_BYTES { return Err(Error::Internal); }
        let mut w = [0u8; REPORT_WORD_BYTES];
        w.copy_from_slice(&self.b[self.i..self.i + REPORT_WORD_BYTES]);
        self.i += REPORT_WORD_BYTES;
        Ok(u64::from_le_bytes(w))
    }
    fn take(&mut self, n: u64) -> Result<Vec<u8>, Error> {
        if n > (self.b.len() - self.i) as u64 { return Err(Error::Internal); }
        let n = n as usize;
        let s = self.b[self.i..self.i + n].to_vec();
        self.i += n;
        Ok(s)
    }
}

/// The report of include/vbm_sse.h, read strictly: every length is checked, nothing may follow.
fn read_report(raw: &[u8]) -> Result<Report, Error> {
    let mut c = Cursor { b: raw, i: 0 };
    let (count, retry_set, retry, id_len) = (c.word()?, c.word()?, c.word()?, c.word()?);
    let last_event_id = c.take(id_len)?;
    let mut events = Vec::new();
    for _ in 0..count {
        let (tl, dl, il) = (c.word()?, c.word()?, c.word()?);
        events.push(Event { type_: c.take(tl)?, data: c.take(dl)?, last_event_id: c.take(il)? });
    }
    if c.i != raw.len() { return Err(Error::Internal); }
    Ok(Report { events, last_event_id, retry: if retry_set == 1 { Some(retry) } else { None } })
}
'''

def gen_rust_lib(d):
    errs = [e for e in d["errors"] if e["value"] != 0]
    s = RS_LIB.replace("@@HDR@@", HDR)
    s = s.replace("@@VARIANTS@@", "\n".join("    %s," % camel(e["name"]) for e in errs))
    s = s.replace("@@CODES@@", "\n".join("            Error::%s => VBM_SSE_%s," % (camel(e["name"]), e["name"]) for e in errs))
    s = s.replace("@@FROM@@", "\n".join("            VBM_SSE_%s => Error::%s," % (e["name"], camel(e["name"])) for e in errs))
    return s

FILES = {
    "bindings/python/vbm_sse/_generated.py": gen_python,
    "bindings/python/vbm_sse/__init__.py": gen_python_init,
    "bindings/rust/src/sys.rs": gen_rust_sys,
    "bindings/rust/src/lib.rs": gen_rust_lib,
}

def main():
    root = sys.argv[1]
    d = json.load(open("abi/vbm_sse.abi.json"))
    for p, f in FILES.items():
        path = os.path.join(root, p)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as fh: fh.write(f(d))
    print("gen_bindings: wrote %d files under %s/bindings" % (len(FILES), root))

if __name__ == "__main__":
    main()
